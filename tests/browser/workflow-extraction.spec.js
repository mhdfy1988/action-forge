import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {addLegacyNode} from './workflow-legacy-fixture.js';

test('真实抽帧工作台：参数、帧检查、播放、复用、失效、刷新恢复',async({page},info)=>{
  const file=info.outputPath('run.mp4');
  execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc2=size=1280x720:rate=24','-t','2','-c:v','libx264','-pix_fmt','yuv420p',file]);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  let jobs=0;page.on('request',request=>{if(request.method()==='POST'&&request.url().endsWith('/api/workflow-extraction/jobs'))jobs++;});
  await page.goto('/workflow');
  await page.locator('.node-tool[data-node-type="action-video"]').click();
  const video=page.locator('.workflow-node[data-node-id^="action-video-"]');
  await video.locator('input[type=file]').setInputFiles(file);
  await expect(video.locator('.mode-mark')).toHaveAttribute('data-status','ready');
  const box=await video.locator('.node-header').boundingBox();
  await page.mouse.move(box.x+40,box.y+10);await page.mouse.down();await page.mouse.move(box.x-310,box.y+10,{steps:10});await page.mouse.up();
  await addLegacyNode(page,'extract-frames');
  const extract=page.locator('.workflow-node[data-node-id^="extract-frames-"]');
  await page.locator('#zoomFit').click();
  const out=await video.locator('.port-dot[data-direction="output"]').boundingBox(),input=await extract.locator('.port-dot[data-direction="input"]').boundingBox();
  await page.mouse.move(out.x+out.width/2,out.y+out.height/2);await page.mouse.down();await page.mouse.move(input.x+input.width/2,input.y+input.height/2,{steps:12});await page.mouse.up();
  await extract.locator('.node-header').click();
  await page.getByRole('button',{name:'打开抽帧工作台',exact:true}).click();
  await expect(page.locator('#extractResultPlayer')).toHaveText('提取后在这里检查序列帧');
  await page.locator('#extractStart').fill('0.5');await page.locator('#extractEnd').fill('1.5');await page.locator('#extractFps').fill('8');
  await page.locator('#extractRun').click();
  await expect(page.locator('#extractResultSummary')).toHaveText('8 帧 · 1280 × 720');
  await expect(page.locator('#extractFrameGrid img')).toHaveCount(8);
  await expect.poll(()=>page.locator('#extractResultPlayer img').evaluate(image=>image.naturalWidth)).toBe(1280);
  await page.locator('#extractFrameGrid button').nth(4).click();
  await expect(page.locator('#extractResultPlayer .frame-player-controls span')).toHaveText('5 / 8');
  await page.locator('#extractResultPlayer').getByRole('button',{name:'播放',exact:true}).click();
  await expect.poll(()=>page.locator('#extractResultPlayer .frame-player-controls span').textContent()).not.toBe('5 / 8');
  await page.locator('#extractResultPlayer').getByRole('button',{name:'暂停',exact:true}).click();
  await page.screenshot({path:info.outputPath('workbench.png')});
  await page.locator('#extractRun').click();await expect(page.locator('#extractRun')).toBeEnabled();expect(jobs).toBe(1);
  await page.locator('#extractFps').fill('12');await page.locator('#extractFps').blur();
  await expect(page.locator('#extractWorkStatus')).toHaveText('待更新');
  await expect(page.locator('#extractResultSummary')).toContainText('旧结果');
  await page.locator('#extractRun').click();await expect(page.locator('#extractResultSummary')).toHaveText('12 帧 · 1280 × 720');
  // 延迟真实后端响应，确定性覆盖点击取消与结果迟到的竞态。
  let release,arrived;
  const received=new Promise(resolve=>arrived=resolve),held=new Promise(resolve=>release=resolve);
  await page.route('**/api/workflow-extraction/jobs',async route=>{const response=await route.fetch();arrived();await held;await route.fulfill({response});});
  await page.locator('#extractFps').fill('10');await page.locator('#extractRun').click();await received;
  await page.locator('#extractCancel').click();release();
  await expect(page.locator('#extractWorkError')).toContainText('已取消');
  await expect(page.locator('#extractRun')).toBeEnabled();
  await expect(page.locator('#extractFrameGrid img')).toHaveCount(12);
  await page.unroute('**/api/workflow-extraction/jobs');
  await page.locator('#extractFps').fill('12');await page.locator('#extractRun').click();
  await expect(page.locator('#extractWorkStatus')).toHaveText('已就绪');
  await page.locator('#backToCanvas').click();
  await expect(extract.locator('.mode-mark')).toHaveAttribute('data-status','ready');
  await expect(page.locator('#parameterFields [data-parameter]')).toHaveCount(0);
  await expect(page.locator('.extract-inspector-summary')).toContainText('0.5 — 1.5 秒');
  await expect(page.locator('.extract-inspector-summary')).toContainText('12 帧 · 1280 × 720');
  await page.screenshot({path:info.outputPath('extract-inspector.png')});
  await page.locator('#flowButton').click();await page.getByRole('button',{name:'新建工作流',exact:true}).click();await page.locator('#libraryName').fill('跳跃');
  // 新建工作流会刷新页面，等待刷新完成后再打开菜单，避免点击落在旧页面。
  await Promise.all([page.waitForNavigation({waitUntil:'load'}),page.locator('#libraryConfirm').click()]);
  await expect(page.locator('.workflow-node')).toHaveCount(0);
  await page.locator('#flowButton').click();await page.locator('#flowList .navigation-select').filter({hasText:'未命名工作流'}).click();
  await expect(extract.locator('.mode-mark')).toHaveAttribute('data-status','ready');
  // 断开任务接口后刷新，证明原始PNG来自本机持久化而非服务器临时任务。
  await page.route('**/api/workflow-extraction/**',route=>route.abort());
  await page.reload();await expect(extract.locator('.mode-mark')).toHaveAttribute('data-status','ready');
  await extract.locator('.node-header').click();await page.getByRole('button',{name:'打开抽帧工作台',exact:true}).click();
  await expect(page.locator('#extractResultSummary')).toHaveText('12 帧 · 1280 × 720');
  await expect.poll(()=>page.locator('#extractResultPlayer img').evaluate(image=>image.naturalWidth)).toBe(1280);
  await page.unroute('**/api/workflow-extraction/**');
  let releaseLate,arrivedLate;
  const lateReceived=new Promise(resolve=>arrivedLate=resolve),lateHeld=new Promise(resolve=>releaseLate=resolve);
  await page.route('**/api/workflow-extraction/jobs',async route=>{const response=await route.fetch();arrivedLate();await lateHeld;await route.fulfill({response});});
  await page.locator('#extractFps').fill('7');await page.locator('#extractRun').click();await lateReceived;
  await page.locator('#backToCanvas').click();await extract.locator('.node-header').click();await page.keyboard.press('Delete');
  await expect(extract).toHaveCount(0);releaseLate();
  await addLegacyNode(page,'extract-frames');
  await expect(extract.locator('.mode-mark')).toHaveAttribute('data-status','idle');
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('action-forge.workflow.r6b.v1')).results.filter(result=>result.nodeId==='extract-frames-1').length)).toBe(0);
  expect(errors).toEqual([]);
});
