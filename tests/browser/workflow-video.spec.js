import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
const key='action-forge.workflow.r6b.v1';
test('动作视频：选择取消、导入播放、刷新恢复、失效和采用确认',async({page},testInfo)=>{
  const file=testInfo.outputPath('action.mp4');
  execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc2=size=160x96:rate=12','-t','1','-c:v','libx264','-pix_fmt','yuv420p',file]);
  await page.goto('/workflow');
  await page.locator('.node-tool[data-node-type="action-video"]').click();
  const node=page.locator('.workflow-node').first(),dot=node.locator('.mode-mark');
  const chooser=page.waitForEvent('filechooser');await node.getByRole('button',{name:'导入动作视频'}).click();await (await chooser).setFiles([]);
  await expect(dot).toHaveAttribute('data-status','idle');
  await node.locator('input[type=file]').setInputFiles(file);
  await expect(dot).toHaveAttribute('data-status','ready');
  await expect(page.locator('#inspectStatus')).toHaveText('已就绪');
  await node.locator('.node-name').dblclick();await node.getByRole('textbox',{name:'节点名称'}).fill('跑步·右');await node.getByRole('textbox',{name:'节点名称'}).press('Enter');
  await expect(dot).toHaveAttribute('data-status','ready');
  await expect(node.locator('.reference-card-dimensions')).toHaveText('160 × 96 像素 · 1.00 秒');
  const video=node.locator('video');
  await video.evaluate(element=>element.play());
  await expect.poll(()=>video.evaluate(element=>element.currentTime)).toBeGreaterThan(0);
  await page.reload();await expect(dot).toHaveAttribute('data-status','ready');
  await expect(video).toBeVisible();
  await node.locator('.node-header').click();
  await page.getByText('生成备注（可选）',{exact:true}).click();
  const prompt=page.locator('#nodeInspector textarea').first();
  await prompt.fill('向左跑步');await prompt.blur();
  await expect(dot).toHaveAttribute('data-status','stale');
  await page.getByRole('button',{name:'采用当前视频',exact:true}).click();
  await page.locator('#adoptVideoDialog').getByRole('button',{name:'取消',exact:true}).click();
  await expect(dot).toHaveAttribute('data-status','stale');
  await page.getByRole('button',{name:'采用当前视频',exact:true}).click();await page.keyboard.press('Escape');
  await expect(dot).toHaveAttribute('data-status','stale');
  await page.getByRole('button',{name:'采用当前视频',exact:true}).click();
  await page.locator('#adoptVideoDialog').getByRole('button',{name:'确认采用',exact:true}).click();
  await expect(dot).toHaveAttribute('data-status','ready');
  // 通过真实画布拖线关联参考图，再换图检查失效传播。
  await page.locator('.node-tool[data-node-type="reference-image"]').click();
  const ref=page.locator('.workflow-node[data-node-id^="reference-image-"]');
  async function imageFile(color){const encoded=await page.evaluate(color=>{const canvas=document.createElement('canvas');canvas.width=80;canvas.height=80;const context=canvas.getContext('2d');context.fillStyle=color;context.fillRect(0,0,80,80);return canvas.toDataURL().split(',')[1];},color);return {name:'角色.png',mimeType:'image/png',buffer:Buffer.from(encoded,'base64')};}
  await ref.locator('input[type=file]').setInputFiles(await imageFile('#888'));
  await expect(ref.locator('.mode-mark')).toHaveAttribute('data-status','ready');
  const header=await ref.locator('.node-header').boundingBox();
  await page.mouse.move(header.x+60,header.y+20);await page.mouse.down();await page.mouse.move(header.x-320,header.y+20,{steps:10});await page.mouse.up();
  await page.locator('#zoomFit').click();
  const output=await ref.locator('.port-dot[data-direction="output"]').boundingBox(),input=await node.locator('.port-dot[data-direction="input"]').boundingBox();
  await page.mouse.move(output.x+output.width/2,output.y+output.height/2);await page.mouse.down();await page.mouse.move(input.x+input.width/2,input.y+input.height/2,{steps:10});await page.mouse.up();
  await expect(dot).toHaveAttribute('data-status','stale');
  await node.locator('.node-header').click();
  await page.getByRole('button',{name:'采用当前视频',exact:true}).click();await page.locator('#adoptVideoDialog').getByRole('button',{name:'确认采用',exact:true}).click();
  await expect(dot).toHaveAttribute('data-status','ready');
  await ref.locator('input[type=file]').setInputFiles(await imageFile('#eee'));
  await expect(dot).toHaveAttribute('data-status','stale');
  await page.reload();await expect(dot).toHaveAttribute('data-status','stale');
  await node.locator('.node-header').click();
  await page.getByRole('button',{name:'采用当前视频',exact:true}).click();await page.locator('#adoptVideoDialog').getByRole('button',{name:'确认采用',exact:true}).click();
  await expect(dot).toHaveAttribute('data-status','ready');
  const original=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).results,key);
  await node.locator('input[type=file]').setInputFiles({name:'坏视频.mp4',mimeType:'video/mp4',buffer:Buffer.from('broken')});
  await expect(dot).toHaveAttribute('data-status','failed');
  expect(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).results,key)).toEqual(original);
  await expect(video).toBeVisible();
  await page.screenshot({path:'output/acceptance/workflow-video-import.png'});
});
